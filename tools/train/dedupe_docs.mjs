// dedupe_docs.mjs — убирает дублирование передачи из ctf-bots-learning.md.
// Канонический вход теперь один: docs/ctf-bots.md, «Часть 1. Передача».
// В learning остаётся короткая ссылка + пометка, что это журнал замеров.
import fs from 'node:fs';

const p = 'docs/ctf-bots-learning.md';
const src = fs.readFileSync(p, 'utf8');
const lines = src.split(/\r?\n/);

// Находим границы блока «⚠ ЧИТАТЬ ПЕРВЫМ» и следующего разделителя `---`.
const start = lines.findIndex((l) => l.startsWith('## ⚠ ЧИТАТЬ ПЕРВЫМ'));
if (start < 0) { console.error('не нашёл блок «ЧИТАТЬ ПЕРВЫМ»'); process.exit(1); }
let end = start;
for (let i = start + 1; i < lines.length; i++) {
  if (lines[i].trim() === '---') { end = i - 1; break; }
}
if (end <= start) { console.error('не нашёл границу блока'); process.exit(1); }

const block = `## Где актуальная информация (2026-10-22)

**Единая точка входа — ТЗ: \`docs/ctf-bots.md\`, «Часть 1. Передача»**: правило
работы, окружение этого ПК, команды запуска, состояние сборки, база метрик,
открытые задачи по приоритету, список откаченных подходов и грабли.

Этот файл — **журнал замеров**: §11–§16 содержат все измерения и разборы,
на которые ссылается ТЗ.

Коротко о состоянии сборки (детали — в ТЗ):
- хитбокс по фигуре (было тело вдвое шире персонажа и со сдвигом вправо);
- флаг не перелетает через платформу при сбросе;
- карта зеркалена (2 опечатки), **баланс смещён к красным**;
- клип в ящик закрыт частично: причина — присед телепортирует тело (§16.7).

**Разделы §0–§10 писались 2026-10-20 и частично НЕВЕРНЫ** (доставка, фитнес,
карта, эскорт): доставка уже работает, фитнес переписан, карта зеркалена.
База метрик для сравнений — в ТЗ, раздел 1.6.
`;

const out = lines.slice(0, start).concat(block.split('\n'), lines.slice(end + 1));
fs.writeFileSync(p, out.join('\n'), 'utf8');
console.log('заменено строк:', end - start + 1, '-> новых:', block.split('\n').length);
console.log('всего строк:', out.length);
