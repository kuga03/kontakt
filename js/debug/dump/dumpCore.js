export function laneOf(p, last) {
  try {
    if (!p || !Number.isFinite(p.x) || !Number.isFinite(p.y)) return null;
    let fy = p.y + 28;
    if (p.body && Number.isFinite(p.body.y) && Number.isFinite(p.body.height)) {
      fy = p.body.y + p.body.height;
    }
    const H = 560, M = 760, h = 30;
    if (last === 'H') return fy < H + h ? 'H' : (fy < M + h ? 'M' : 'L');
    if (last === 'M') return fy > M + h ? 'L' : (fy < H - h ? 'H' : 'M');
    if (last === 'L') return fy < H - h ? 'H' : (fy < M - h ? 'M' : 'L');
    return fy < H ? 'H' : (fy < M ? 'M' : 'L');
  } catch (e) { return null; }
}

export function clipboardFallback(scene, text, done) {
  try {
    if (scene && scene.game && scene.game.device && scene.game.device.os &&
        typeof window !== 'undefined' && window.clipboardData) {
      try { window.clipboardData.setData('Text', text); done && done(true); return; } catch (e) {}
    }
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    let ok = false;
    try { ok = document.execCommand('copy'); } catch (e) { ok = false; }
    try { document.body.removeChild(ta); } catch (e) {}
    done && done(ok);
  } catch (e) { done && done(false); }
}

