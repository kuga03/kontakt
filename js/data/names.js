const RU_NAMES = [
  // Позывные, как в нормальных лобби: звери, стихия, характер.
  // Без цифр, годов, клантегов и мемов.
  'Волк', 'Барс', 'Сокол', 'Ястреб', 'Беркут',
  'Тигр', 'Медведь', 'Рысь', 'Соболь', 'Коршун',
  'Гром', 'Тайфун', 'Шторм', 'Вихрь', 'Буран',
  'Молния', 'Смерч', 'Град', 'Ураган', 'Мороз',
  'Клинок', 'Щит', 'Молот', 'Штык', 'Гранит',
  'Сталь', 'Кремень', 'Базальт', 'Титан', 'Агат',
  'Страж', 'Часовой', 'Разведчик', 'Следопыт', 'Егерь',
  'Ветеран', 'Старшина', 'Сержант', 'Казак', 'Гусар',
  'Хан', 'Сармат', 'Атаман', 'Ермак', 'Добрыня',
  'Север', 'Восток', 'Скала', 'Утёс', 'Кедр'
];

export function randomBotNames(count, exclude = []) {
  const pool = RU_NAMES.filter(n => !exclude.includes(n)).slice();

  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  return pool.slice(0, Math.max(0, count));
}
